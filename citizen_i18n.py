def category_value_from_label(label: str, language: str = "en") -> str | None:
    """Maps a translated category label back to its canonical stored value."""
    for canonical in CATEGORY_TRANSLATIONS:
        if canonical != "Select a category..." and translate_category(canonical, language) == label:
            return canonical
    return None


