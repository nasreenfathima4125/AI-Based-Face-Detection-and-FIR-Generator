def translate(key: str, language: str = "en", **values: Any) -> str:
    """Returns a localized string, falling back safely to English and then key."""
    selected = TRANSLATIONS.get(language, TRANSLATIONS["en"])
    template = selected.get(key, TRANSLATIONS["en"].get(key, key))
    try:
        return template.format(**values)
    except (KeyError, ValueError):
        return template


def translate_validation_message(message: str, language: str = "en") -> str:
    """Localizes existing validator messages without changing validation rules."""
    key = VALIDATION_KEYS.get(message)
    return translate(key, language) if key else message


def translate_feedback(message: str, language: str = "en") -> str:
    """Localizes a known workflow feedback string, preserving safe fallbacks."""
    key = VALIDATION_KEYS.get(message) or FEEDBACK_KEYS.get(message)
    return translate(key, language) if key else message


